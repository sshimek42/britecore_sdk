#!/usr/bin/env python3
"""
Fix remaining multi-line autogenerated docstrings to new concise format.

Converts docstrings from verbose Args/Returns/Raises format to:
\"\"\"[Description] ([METHOD] /api/v2/[endpoint]).\"\"\"
"""

import re
import sys
from pathlib import Path

FILES_TO_FIX = [
    "src/britecore_sdk/api/api_calls/v2/async_contacts.py",
    "src/britecore_sdk/api/api_calls/v2/async_lines.py",
    "src/britecore_sdk/api/api_calls/v2/async_policies.py",
    "src/britecore_sdk/api/api_calls/v2/authority_limits.py",
    "src/britecore_sdk/api/api_calls/v2/claim_catastrophes.py",
    "src/britecore_sdk/api/api_calls/v2/claim_contacts.py",
    "src/britecore_sdk/api/api_calls/v2/claim_dates.py",
    "src/britecore_sdk/api/api_calls/v2/claim_exposures.py",
    "src/britecore_sdk/api/api_calls/v2/claim_vehicles.py",
    "src/britecore_sdk/api/api_calls/v2/deliverables.py",
    "src/britecore_sdk/api/api_calls/v2/lines.py",
    "src/britecore_sdk/api/api_calls/v2/named_insureds.py",
    "src/britecore_sdk/api/api_calls/v2/quotes.py",
    "src/britecore_sdk/api/api_calls/v2/utils.py",
]

# Pattern to match multi-line docstrings with Args/Returns/Raises
DOCSTRING_PATTERN = re.compile(
    r'"""([^"]+?)\n\n\s+Send a request to[^.]*?\..*?(?:Returns processed result[^.]*?\.|QueryLanguage[^.]*?\.)\n\n\s+Args:\n(.*?)\n\n\s+Returns:\n.*?\n\n\s+Raises:\n.*?"""',
    re.DOTALL
)

# Pattern to extract method and endpoint from docstring text
METHOD_ENDPOINT_PATTERN = re.compile(
    r'(?:POST|GET|PUT|DELETE|PATCH)\s+(/api/v2/[^\s"]+)'
)


def extract_description(text: str) -> str:
    """Extract the first line (description) from docstring."""
    lines = text.strip().split('\n')
    return lines[0].strip() if lines else ""


def extract_method_endpoint(docstring: str) -> tuple[str, str]:
    """Extract HTTP method and endpoint from docstring."""
    # Look for patterns like "POST /api/v2/endpoint"
    match = re.search(r'(POST|GET|PUT|DELETE|PATCH)\s+(/api/v2/[^\s`,".]+)', docstring)
    if match:
        return match.group(1), match.group(2)

    # If not found, try to infer from context - look for the path in backticks
    path_match = re.search(r'``(/api/v2/[^\s`]+)``', docstring)
    if path_match:
        # Default to POST for most operations
        return "POST", path_match.group(1)

    return "", ""


def create_new_docstring(description: str, method: str, endpoint: str) -> str:
    """Create new concise one-liner docstring."""
    if method and endpoint:
        return f'"""{description} ({method} {endpoint})."""'
    return f'"""{description}."""'


def process_file(file_path: Path) -> int:
    """
    Process a single file and convert docstrings.

    Returns the number of docstrings fixed.
    """
    if not file_path.exists():
        print(f"File not found: {file_path}")
        return 0

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    original_content = content
    count = 0

    # Find all function definitions and their docstrings
    # Pattern: def function_name(...): followed by docstring
    func_pattern = re.compile(
        r'(def\s+\w+\([^)]*\)[^:]*:\n\s+)"""([^"]+?)(?:\n\n\s+Send a request to[^.]*?\..*?(?:Returns processed result[^.]*?\.|QueryLanguage[^.]*?\.)\n\n\s+Args:.*?\n\n\s+Returns:.*?\n\n\s+Raises:.*?)?"""',
        re.DOTALL
    )

    def replace_docstring(match):
        nonlocal count
        func_def = match.group(1)
        docstring_text = match.group(2)

        # Extract first line as description
        description = extract_description(docstring_text)

        # Try to extract method and endpoint
        full_match = match.group(0)
        method, endpoint = extract_method_endpoint(full_match)

        # Create new docstring
        new_docstring = create_new_docstring(description, method, endpoint)
        count += 1

        return func_def + new_docstring

    content = func_pattern.sub(replace_docstring, content)

    if content != original_content:
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"✓ {file_path.name}: {count} docstrings fixed")
    else:
        print(f"  {file_path.name}: no changes needed")

    return count


def main():
    """Main entry point."""
    base_path = Path.cwd()
    total_fixed = 0

    for file_rel_path in FILES_TO_FIX:
        file_path = base_path / file_rel_path
        fixed = process_file(file_path)
        total_fixed += fixed

    print(f"\n{'=' * 60}")
    print(f"Total docstrings fixed: {total_fixed}")
    return 0 if total_fixed > 0 else 1


if __name__ == "__main__":
    sys.exit(main())

