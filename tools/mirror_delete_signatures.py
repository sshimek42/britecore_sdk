"""Conservative mirroring: copy signatures/request_json from paired get_*/retrieve_*

This script scans autogenerated v2 wrapper modules and for any function whose
name starts with ``delete_`` and whose `request_json` is empty (``{}``), it
attempts to find a sibling function in the same module with the same name
suffix but a ``get_`` or ``retrieve_`` prefix that has a non-empty
`request_json`. When found, the script copies the parameter signature and the
`request_json` body into the delete_* function.

This is intentionally conservative: it only mirrors when the suffix matches
exactly and the donor function exists in the same module. Run with
``--dry-run`` to preview changes.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
API_CALLS_V2 = REPO_ROOT / "src" / "britecore_sdk" / "api" / "api_calls" / "v2"


def _collect_functions(source: str) -> dict[str, Tuple[str, str, str]]:
    """Return mapping name -> (full_block, signature_block, request_json_block).

    signature_block is the text between the opening "def name(" and the
    closing ") -> Any:\n" (inclusive of newlines). request_json_block is the
    literal lines for the request_json assignment, e.g.
    "    request_json: dict[str, Any] = {}\n" or a multiline dict.
    """
    functions: dict[str, Tuple[str, str, str]] = {}

    # We'll scan function blocks and extract signature/request_json using
    # simpler, targeted regexes rather than one giant pattern to avoid
    # catastrophic backtracking and keep the matching conservative.

    # Simpler, deterministic parser: split on '\ndef ' boundaries
    src = "\n" + source
    parts = src.split("\ndef ")
    for part in parts[1:]:
        # restore leading 'def '
        block = "def " + part

        # function name is up to first '('
        fn_name_end = block.find("(")
        if fn_name_end == -1:
            continue
        name = block[4:fn_name_end].strip()

        # find signature end marker
        sig_end_marker = ") -> Any:\n"
        sig_end_idx = block.find(sig_end_marker)
        if sig_end_idx == -1:
            continue
        signature_block = block[: sig_end_idx + len(sig_end_marker)]

        # find request_json assignment
        rq_key = "request_json: dict[str, Any] ="
        rq_idx = block.find(rq_key)
        request_json_block = ""
        if rq_idx != -1:
            # Find the start of the line to preserve indentation
            line_start = block.rfind("\n", 0, rq_idx) + 1
            if line_start == 0:  # rfind returns -1 if not found
                line_start = 0
            indent = block[line_start : rq_idx]

            # slice starting at assignment
            rq_slice = block[rq_idx:]
            # if it's the simple empty dict on the same line
            if rq_slice.startswith(rq_key + " {}") or rq_slice.startswith(rq_key + " {}\n"):
                request_json_block = indent + "request_json: dict[str, Any] = {}\n"
            else:
                # multiline dict — locate the opening '{' and closing brace
                brace_idx = rq_slice.find("{")
                if brace_idx != -1:
                    # scan lines until a line that equals indent + '}'
                    lines = rq_slice.splitlines(keepends=True)
                    collected = []
                    open_braces = 0
                    started = False
                    for line in lines:
                        collected.append(line)
                        if "{" in line:
                            started = True
                            open_braces += line.count("{")
                        if "}" in line and started:
                            open_braces -= line.count("}")
                            if open_braces <= 0:
                                break
                    request_json_block = indent + "".join(collected)

        functions[name] = (block, signature_block, request_json_block)

    return functions


def _mirror_in_module(module_path: Path, dry_run: bool = True) -> list[str]:
    src = module_path.read_text(encoding="utf-8")
    funcs = _collect_functions(src)
    changes: list[str] = []
    updated_src = src

    for name, (block, signature_block, request_json_block) in funcs.items():
        if not name.startswith("delete_"):
            continue

        # Only act if request_json is empty
        if request_json_block and "{}" not in request_json_block:
            # has non-empty body
            continue

        suffix = name[len("delete_"):]
        donor = None
        for prefix in ("get_", "retrieve_"):
            cand = prefix + suffix
            if cand in funcs:
                donor = cand
                break

        if not donor:
            changes.append(f"SKIP {module_path.name}: no donor for {name}")
            continue

        donor_block, donor_signature, donor_request_json = funcs[donor]
        if not donor_request_json or "{}" in donor_request_json:
            changes.append(f"SKIP {module_path.name}: donor {donor} has no body")
            continue

        # Build new function text: inject donor_signature before **kwargs line & replace request_json
        new_block = block

        # 1) Replace the simple '**kwargs' signature with donor params + **kwargs
        # Locate the '**kwargs' line in the signature_block
        kw_line = "    **kwargs: Unpack[RequestParameters],\n"
        if kw_line in signature_block:
            # Extract opening "def delete_...(" part from original signature
            opening_end = signature_block.find("(\n")
            if opening_end == -1:
                changes.append(f"WARN {module_path.name}: could not parse opening in {name}")
                continue
            opening = signature_block[: opening_end + 2]  # includes "def delete_...(\n"

            # Extract donor params (without "def get_..." and ")\n")
            donor_params = donor_signature.replace("def ", "").split("(\n", 1)[-1]
            # donor_params currently includes the closing ") -> Any:\n"; we want the params only
            donor_params_only = donor_params.rsplit(") -> Any:\n", 1)[0]
            # Remove trailing **kwargs line from donor_params (we'll add it back)
            if donor_params_only.endswith("    **kwargs: Unpack[RequestParameters],\n"):
                donor_params_only = donor_params_only[: -len("    **kwargs: Unpack[RequestParameters],\n")]
            # Build replacement signature: keep opening, add donor params (without **kwargs), add **kwargs, add closing
            replacement_signature = opening + donor_params_only + "    **kwargs: Unpack[RequestParameters],\n) -> Any:\n"
            new_block = new_block.replace(signature_block, replacement_signature, 1)
        else:
            changes.append(f"WARN {module_path.name}: could not locate **kwargs in {name}")
            continue

        # 2) Replace empty request_json with donor_request_json
        if "request_json: dict[str, Any] = {}" in new_block:
            new_block = new_block.replace("    request_json: dict[str, Any] = {}\n", donor_request_json, 1)
        else:
            changes.append(f"WARN {module_path.name}: could not locate empty request_json in {name}")
            continue

        if block != new_block:
            updated_src = updated_src.replace(block, new_block, 1)
            changes.append(f"UPDATE {module_path.name}: mirrored {donor} -> {name}")

    if changes and not dry_run:
        module_path.write_text(updated_src, encoding="utf-8")

    return changes


def main(argv: list[str] | None = None) -> int:
    """Mirror delete_* function signatures from donor functions in v2 API modules.

    Scans all API call modules in api_calls/v2 and for each delete_* function,
    attempts to find a corresponding get_* or retrieve_* function (donor) with
    the same core name. Mirrors the donor's signature parameters into the delete
    function. Changes are applied conservatively (only replacing simple parameter
    patterns). Supports dry-run mode to preview changes without writing.

    Args:
        argv: Optional command-line arguments. If None, parses sys.argv.
              Supported: --dry-run to preview without writing files.

    Returns:
        int: Exit code (always 0 on success; argparse exits non-zero on error).

    Example:
        >>> main(["--dry-run"])  # Show proposed changes without writing
        0
    """
    parser = argparse.ArgumentParser(description="Mirror delete_* signatures from get_*/retrieve_* donors")
    parser.add_argument("--dry-run", action="store_true", help="Show changes but do not write files")
    args = parser.parse_args(argv)

    all_changes: list[str] = []
    for module in sorted(API_CALLS_V2.glob("*.py")):
        changes = _mirror_in_module(module, dry_run=args.dry_run)
        if changes:
            print(f"\n{'DRY-RUN ' if args.dry_run else ''}Processing: {module.name}")
            for c in changes:
                print(f"  {c}")
            all_changes.extend(changes)

    if not all_changes:
        print("No conservative mirroring changes detected.")
    else:
        print(f"\n{'DRY-RUN ' if args.dry_run else ''}Done — {len(all_changes)} change(s) reported.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())

