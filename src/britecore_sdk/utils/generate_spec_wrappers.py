"""Generate and sync spec-backed endpoint wrappers.

This utility keeps ``src/britecore_sdk/api/api_calls/{v1,v2}`` aligned with
``api_specs/current/britecore.json`` by:

1. Discovering spec paths missing wrapper literals.
2. Distributing new wrappers into version/domain modules.
3. Regenerating ``# --- Autogenerated spec wrappers ---`` blocks with explicit
   endpoint parameters inferred from request schemas.
"""

from __future__ import annotations

import argparse
import ast
import json
import keyword
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

MARKER = "# --- Autogenerated spec wrappers ---"
VALID_METHODS = {"get", "post", "put", "patch", "delete"}


@dataclass(frozen=True)
class Endpoint:
    path: str
    method: str


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _api_calls_root(repo_root: Path) -> Path:
    return repo_root / "src" / "britecore_sdk" / "api" / "api_calls"


def _load_spec(spec_path: Path) -> dict[str, Any]:
    payload = json.loads(spec_path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError("Spec payload is not a dictionary")
    return payload


def _spec_paths(spec_payload: dict[str, Any]) -> dict[str, dict[str, Any]]:
    paths = spec_payload.get("paths", {})
    if not isinstance(paths, dict):
        raise ValueError("Spec `paths` is not a dictionary")
    return paths


def _resolve_local_schema_ref(
    schema: dict[str, Any],
    components: dict[str, Any],
) -> dict[str, Any]:
    ref = schema.get("$ref")
    if not isinstance(ref, str) or not ref.startswith("#/components/schemas/"):
        return schema

    schema_name = ref.rsplit("/", 1)[-1]
    schemas = components.get("schemas", {})
    if not isinstance(schemas, dict):
        return schema
    resolved = schemas.get(schema_name)
    if not isinstance(resolved, dict):
        return schema
    return resolved


def _extract_path_literals(py_file: Path) -> set[str]:
    tree = ast.parse(py_file.read_text(encoding="utf-8"))
    paths: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        for arg in node.args:
            if (
                isinstance(arg, ast.Constant)
                and isinstance(arg.value, str)
                and arg.value.startswith("/api/")
            ):
                paths.add(arg.value)
        for kw in node.keywords:
            if (
                kw.arg == "path"
                and isinstance(kw.value, ast.Constant)
                and isinstance(kw.value.value, str)
                and kw.value.value.startswith("/api/")
            ):
                paths.add(kw.value.value)
    return paths


def _implemented_paths(api_calls_root: Path) -> set[str]:
    implemented: set[str] = set()
    for py_file in api_calls_root.rglob("*.py"):
        if py_file.name == "__init__.py":
            continue
        implemented.update(_extract_path_literals(py_file))
    return implemented


def _sanitize_identifier(raw: str) -> str:
    text = re.sub(r"[^0-9A-Za-z_]+", "_", raw).strip("_")
    if not text:
        text = "field"
    if text[0].isdigit():
        text = f"f_{text}"
    if keyword.iskeyword(text):
        text = f"{text}_"
    return text


def _snake_name(raw: str) -> str:
    return _sanitize_identifier(raw).lower()


def _module_for_path(api_calls_root: Path, endpoint_path: str) -> Path | None:
    match = re.match(r"^/api/(v[12])/([^/]+)/", endpoint_path)
    if not match:
        return None
    version, domain = match.groups()
    return api_calls_root / version / f"{_snake_name(domain)}.py"


def _function_name_for_path(path: str, method: str, existing: set[str]) -> str:
    action = path.rsplit("/", 1)[-1]
    base = _snake_name(action)
    candidate = base
    if candidate in existing:
        candidate = f"{base}_{method.lower()}"
    suffix = 2
    while candidate in existing:
        candidate = f"{base}_{suffix}"
        suffix += 1
    existing.add(candidate)
    return candidate


def _parse_existing_function_names(module_text: str) -> set[str]:
    tree = ast.parse(module_text)
    return {node.name for node in tree.body if isinstance(node, ast.FunctionDef)}


def _ensure_module_file(module_path: Path) -> None:
    if module_path.exists():
        return
    version_label = module_path.parent.name.upper()
    domain = module_path.stem
    module_path.write_text(
        (
            f'"""BriteCore {version_label} {domain} API endpoint wrappers."""\n\n'
            "from typing import Any, Unpack\n\n"
            "from britecore_sdk.api.api_calls import RequestParameters\n"
        ),
        encoding="utf-8",
    )


def _collect_method_map(spec_paths: dict[str, dict[str, Any]]) -> dict[str, list[str]]:
    method_map: dict[str, list[str]] = {}
    for path, operations in spec_paths.items():
        methods: list[str] = []
        if isinstance(operations, dict):
            methods = [
                method.upper()
                for method in operations
                if isinstance(method, str) and method.lower() in VALID_METHODS
            ]
        method_map[path] = sorted(set(methods or ["POST"]))
    return method_map


def _append_missing_endpoints(
    api_calls_root: Path,
    missing: list[str],
    method_map: dict[str, list[str]],
) -> dict[str, set[str]]:
    new_modules: dict[str, set[str]] = {"v1": set(), "v2": set()}
    grouped: dict[Path, list[Endpoint]] = {}
    for path in missing:
        module_path = _module_for_path(api_calls_root, path)
        if module_path is None:
            continue
        for method in method_map.get(path, ["POST"]):
            grouped.setdefault(module_path, []).append(
                Endpoint(path=path, method=method)
            )

    for module_path, endpoints in grouped.items():
        _ensure_module_file(module_path)
        text = module_path.read_text(encoding="utf-8")
        if MARKER in text:
            prefix, section = text.split(MARKER, 1)
            existing_defs = _parse_existing_function_names(prefix + MARKER + section)
        else:
            prefix, section = text, ""
            existing_defs = _parse_existing_function_names(text)

        pending: list[tuple[str, Endpoint]] = []
        for endpoint in endpoints:
            fn_name = _function_name_for_path(
                endpoint.path, endpoint.method, existing_defs
            )
            pending.append((fn_name, endpoint))

        if not pending:
            continue

        existing_section = section.strip()
        new_lines: list[str] = [existing_section] if existing_section else []
        for fn_name, endpoint in pending:
            new_lines.append(
                f"\ndef {fn_name}(\n"
                "    **kwargs: Unpack[RequestParameters],\n"
                ") -> Any:\n"
                f'    """Autogenerated wrapper for ``{endpoint.method} {endpoint.path}``."""\n'
                "    from britecore_sdk.api.api_calls import api_client as _api_client\n\n"
                "    request_json: dict[str, Any] = {}\n"
                "    filtered_json = {k: v for k, v in request_json.items() if v is not None}\n"
                "    request_result = API_CLIENT.do_request(\n"
                f'        path="{endpoint.path}",\n'
                "        json=filtered_json,\n"
                f'        method="{endpoint.method}",\n'
                "        **kwargs,\n"
                "    )\n"
                f'    return API_CLIENT.process_result(request_result, endpoint="{endpoint.path}")\n'
            )

        has_all = "__all__ =" in prefix
        names = [name for name, _ in pending]
        if has_all:
            all_block = (
                "__all__.extend([\n"
                + "".join(f'    "{name}",\n' for name in names)
                + "])\n"
            )
        else:
            all_block = (
                "__all__ = [\n" + "".join(f'    "{name}",\n' for name in names) + "]\n"
            )
        rebuilt = (
            prefix.rstrip()
            + "\n\n"
            + MARKER
            + "\n"
            + "\n".join(new_lines).rstrip()
            + "\n\n"
            + all_block
        )
        module_path.write_text(rebuilt, encoding="utf-8")

        ver = module_path.parent.name
        if ver in new_modules:
            new_modules[ver].add(module_path.stem)

    return new_modules


def _update_version_init(api_calls_root: Path, version: str, modules: set[str]) -> None:
    if not modules:
        return
    init_path = api_calls_root / version / "__init__.py"
    text = init_path.read_text(encoding="utf-8")
    import_line = (
        f"from britecore_sdk.api.api_calls.{version} import "
        + ", ".join(sorted(modules))
        + "\n"
    )
    if import_line not in text:
        text = text.rstrip() + "\n" + import_line

    all_match = re.search(r"__all__\s*=\s*\[(.*?)\]", text, re.S)
    if all_match:
        body = all_match.group(1)
        existing = set(re.findall(r'"([A-Za-z0-9_]+)"', body))
        additions = [module for module in sorted(modules) if module not in existing]
        if additions:
            body = body.rstrip() + "".join(f', "{name}"' for name in additions)
            text = text[: all_match.start(1)] + body + text[all_match.end(1) :]
    init_path.write_text(text, encoding="utf-8")


def _merge_type_names(type_names: list[str]) -> str:
    unique = []
    for name in type_names:
        if name not in unique:
            unique.append(name)
    if not unique:
        return "Any"
    if len(unique) == 1:
        return unique[0]
    return " | ".join(unique)


def _infer_type(schema: Any) -> str:
    if not isinstance(schema, dict):
        return "Any"

    if "$ref" in schema:
        return "dict[str, Any]"

    unions: list[str] = []
    for key in ("anyOf", "oneOf", "allOf"):
        entries = schema.get(key)
        if isinstance(entries, list):
            unions.extend(_infer_type(entry) for entry in entries)

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        unions.extend(
            _infer_primitive_type(t, schema) for t in schema_type if isinstance(t, str)
        )
    elif isinstance(schema_type, str):
        unions.append(_infer_primitive_type(schema_type, schema))

    if not unions and "enum" in schema:
        enum_values = schema.get("enum")
        if isinstance(enum_values, list):
            enum_types: list[str] = []
            for value in enum_values:
                if isinstance(value, bool):
                    enum_types.append("bool")
                elif isinstance(value, int) and not isinstance(value, bool):
                    enum_types.append("int")
                elif isinstance(value, float):
                    enum_types.append("float")
                elif isinstance(value, str):
                    enum_types.append("str")
            return _merge_type_names(enum_types) or "Any"

    return _merge_type_names(unions)


def _infer_primitive_type(schema_type: str, schema: dict[str, Any]) -> str:
    if schema_type == "string":
        return "str"
    if schema_type == "integer":
        return "int"
    if schema_type == "number":
        return "float | int"
    if schema_type == "boolean":
        return "bool"
    if schema_type == "array":
        items = schema.get("items")
        item_type = _infer_type(items)
        return f"list[{item_type}]"
    if schema_type == "object":
        return "dict[str, Any]"
    return "Any"


def _operation_schema(
    spec_paths: dict[str, dict[str, Any]],
    components: dict[str, Any],
    endpoint: Endpoint,
) -> dict[str, Any]:
    operations = spec_paths.get(endpoint.path, {})
    if not isinstance(operations, dict):
        return {}
    op = operations.get(endpoint.method.lower(), {})
    if not isinstance(op, dict):
        return {}
    request_body = op.get("requestBody", {})
    if not isinstance(request_body, dict):
        return {}
    content = request_body.get("content", {})
    if not isinstance(content, dict):
        return {}
    app_json = content.get("application/json", {})
    if not isinstance(app_json, dict):
        return {}
    schema = app_json.get("schema", {})
    if not isinstance(schema, dict):
        return {}
    return _resolve_local_schema_ref(schema, components)


def _parse_autogen_entries(section: str) -> list[tuple[str, Endpoint]]:
    pattern = re.compile(
        r'def\s+([A-Za-z0-9_]+)\((?:.|\n)*?\)\s*->\s*Any:\s*\n\s*"""Autogenerated wrapper for ``([A-Z]+)\s+(/api/[^`]+)``\."""',
        re.MULTILINE,
    )
    return [
        (match.group(1), Endpoint(path=match.group(3), method=match.group(2)))
        for match in pattern.finditer(section)
    ]


def _render_autogen_function(
    fn_name: str,
    endpoint: Endpoint,
    spec_paths: dict[str, dict[str, Any]],
    components: dict[str, Any],
) -> str:
    schema = _operation_schema(spec_paths, components, endpoint)
    properties = schema.get("properties", {})
    props = properties if isinstance(properties, dict) else {}

    used_names: set[str] = set()
    args: list[tuple[str, str, str]] = []
    for prop_name, prop_schema in props.items():
        py_name = _sanitize_identifier(prop_name)
        while py_name in used_names:
            py_name += "_"
        used_names.add(py_name)
        annotation = _infer_type(prop_schema)
        args.append((py_name, prop_name, annotation))

    signature = "".join(
        f"    {py_name}: {annotation} | None = None,\n"
        for py_name, _, annotation in args
    )
    signature += "    **kwargs: Unpack[RequestParameters],\n"

    if args:
        request_json = (
            "    request_json: dict[str, Any] = {\n"
            + "".join(
                f'        "{api_name}": {py_name},\n' for py_name, api_name, _ in args
            )
            + "    }\n"
        )
    else:
        request_json = "    request_json: dict[str, Any] = {}\n"

    return (
        f"def {fn_name}(\n"
        f"{signature}"
        ") -> Any:\n"
        f'    """Autogenerated wrapper for ``{endpoint.method} {endpoint.path}``."""\n'
        "    from britecore_sdk.api.api_calls import api_client as _api_client\n\n"
        f"{request_json}"
        "    filtered_json = {k: v for k, v in request_json.items() if v is not None}\n"
        "    request_result = API_CLIENT.do_request(\n"
        f'        path="{endpoint.path}",\n'
        "        json=filtered_json,\n"
        f'        method="{endpoint.method}",\n'
        "        **kwargs,\n"
        "    )\n"
        f'    return API_CLIENT.process_result(request_result, endpoint="{endpoint.path}")\n'
    )


def _regenerate_autogen_sections(
    api_calls_root: Path,
    spec_paths: dict[str, dict[str, Any]],
    components: dict[str, Any],
) -> int:
    updated = 0
    for py_file in sorted((api_calls_root / "v1").glob("*.py")) + sorted(
        (api_calls_root / "v2").glob("*.py")
    ):
        if py_file.name == "__init__.py":
            continue
        text = py_file.read_text(encoding="utf-8")
        if MARKER not in text:
            continue
        prefix, section = text.split(MARKER, 1)
        entries = _parse_autogen_entries(section)
        if not entries:
            continue

        rendered = "\n\n".join(
            _render_autogen_function(fn_name, endpoint, spec_paths, components)
            for fn_name, endpoint in entries
        )
        names = [fn_name for fn_name, _ in entries]
        has_all = "__all__ =" in prefix
        if has_all:
            all_block = (
                "__all__.extend([\n"
                + "".join(f'    "{name}",\n' for name in names)
                + "])\n"
            )
        else:
            all_block = (
                "__all__ = [\n" + "".join(f'    "{name}",\n' for name in names) + "]\n"
            )

        rebuilt = (
            prefix.rstrip() + "\n\n" + MARKER + "\n\n" + rendered + "\n\n" + all_block
        )
        if rebuilt != text:
            py_file.write_text(rebuilt, encoding="utf-8")
            updated += 1
    return updated


def _restore_common_imports(api_calls_root: Path) -> int:
    updated = 0
    import_line = (
        "from britecore_sdk.api.api_calls.v2._common import build_payload, post"
    )
    for py_file in sorted((api_calls_root / "v2").glob("*.py")):
        if py_file.name in {"__init__.py", "_common.py"}:
            continue
        text = py_file.read_text(encoding="utf-8")
        uses_helpers = (
            "build_payload(" in text or re.search(r"\bpost\(", text) is not None
        )
        if not uses_helpers or import_line in text:
            continue

        lines = text.splitlines()
        insert_index = 0
        for i, line in enumerate(lines):
            if line.startswith(
                "from britecore_sdk.api.api_calls import RequestParameters"
            ):
                insert_index = i + 1
                break
        lines.insert(insert_index, import_line)
        py_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
        updated += 1
    return updated


def sync_wrappers(spec_path: Path) -> dict[str, int]:
    repo_root = _repo_root()
    api_calls_root = _api_calls_root(repo_root)
    spec_payload = _load_spec(spec_path)
    spec_paths = _spec_paths(spec_payload)
    components = spec_payload.get("components", {})
    if not isinstance(components, dict):
        components = {}
    method_map = _collect_method_map(spec_paths)

    implemented = _implemented_paths(api_calls_root)
    missing = sorted(set(spec_paths.keys()) - implemented)
    new_modules = _append_missing_endpoints(api_calls_root, missing, method_map)
    _update_version_init(api_calls_root, "v1", new_modules["v1"])
    _update_version_init(api_calls_root, "v2", new_modules["v2"])
    imports_restored = _restore_common_imports(api_calls_root)
    rewritten = _regenerate_autogen_sections(api_calls_root, spec_paths, components)

    post_sync_implemented = _implemented_paths(api_calls_root)
    remaining = len(set(spec_paths.keys()) - post_sync_implemented)
    return {
        "missing_before": len(missing),
        "modules_rewritten": rewritten,
        "remaining_missing": remaining,
        "new_v1_modules": len(new_modules["v1"]),
        "new_v2_modules": len(new_modules["v2"]),
        "imports_restored": imports_restored,
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Sync autogenerated API wrappers with api_specs/current/britecore.json"
    )
    parser.add_argument(
        "--spec",
        type=Path,
        default=_repo_root() / "api_specs" / "current" / "britecore.json",
        help="Path to OpenAPI/JSON spec file",
    )
    args = parser.parse_args()
    result = sync_wrappers(args.spec)
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
